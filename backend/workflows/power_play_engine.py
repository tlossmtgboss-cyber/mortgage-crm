"""
Power Play Workflow Engine - 7 Workflows per PRD
TL Development, LLC

Implements the 7 Power Play Workflows:
1. Prospect Power Play - Active buyers with 10-month timeline
2. PreQual Power Play - Soft-pulled, financially ready
3. Pre-Approved Power Play - Under contract with tight timelines
4. Long-Term Nurture Power Play - 10+ month buyers (passive)
5. Under Contract Power Play - Active loan management
6. Consumer Referral Power Play - Past clients with referral potential
7. Circle of Cash Flow Power Play - Realtor/professional referral management
"""

from datetime import datetime, timedelta, timezone
from typing import List, Dict, Optional, Any, Tuple
from dataclasses import dataclass, field
from enum import Enum
from sqlalchemy.orm import Session
from sqlalchemy import text
import json
import logging

logger = logging.getLogger(__name__)


# ==============================================================================
# POWER PLAY WORKFLOW TYPES
# ==============================================================================

class PowerPlayType(str, Enum):
    PROSPECT = "prospect_power_play"
    PREQUAL = "prequal_power_play"
    PRE_APPROVED = "pre_approved_power_play"
    LONG_TERM_NURTURE = "long_term_nurture_power_play"
    UNDER_CONTRACT = "under_contract_power_play"
    CONSUMER_REFERRAL = "consumer_referral_power_play"
    CIRCLE_OF_CASH_FLOW = "circle_of_cash_flow_power_play"


class WorkflowActionType(str, Enum):
    TASK = "task"
    EMAIL = "email"
    SMS = "sms"
    ALERT = "alert"
    TAG = "tag"
    DRIP_CAMPAIGN = "drip_campaign"
    STAGE_CHANGE = "stage_change"
    SCHEDULE_TOUCH = "schedule_touch"
    RATE_LOCK_CHECK = "rate_lock_check"


# ==============================================================================
# DATA MODELS
# ==============================================================================

@dataclass
class TouchFrequency:
    """Touch frequency based on buying timeline"""
    platinum: int = 7    # < 3 months, every 7 days
    gold: int = 14       # 4-6 months, every 14 days
    silver: int = 21     # 7-9 months, every 21 days
    green: int = 30      # 10+ months, monthly


@dataclass
class PowerPlayAction:
    """Action generated by a Power Play workflow"""
    action_type: WorkflowActionType
    target: str  # lead, loan_officer, referral_source
    data: Dict[str, Any]
    priority: str = "normal"  # low, normal, high, urgent
    scheduled_for: Optional[datetime] = None
    template: Optional[str] = None


@dataclass
class PowerPlayResult:
    """Result of processing a Power Play workflow"""
    workflow_type: PowerPlayType
    entity_id: int
    entity_type: str  # lead, loan, contact
    actions: List[PowerPlayAction] = field(default_factory=list)
    next_touch_date: Optional[datetime] = None
    status: str = "processed"
    message: str = ""


# ==============================================================================
# POWER PLAY WORKFLOW ENGINE
# ==============================================================================

class PowerPlayEngine:
    """Main engine for processing all 7 Power Play workflows"""

    def __init__(self, db: Session):
        self.db = db
        self.touch_frequency = TouchFrequency()

    # ==========================================================================
    # MAIN ENTRY POINTS
    # ==========================================================================

    def process_lead_workflow(self, lead: Any, trigger: str = None) -> PowerPlayResult:
        """
        Determine and execute appropriate Power Play for a lead.

        Triggers:
        - stage_change: Lead stage changed
        - timeline_update: Buying timeline updated
        - new_lead: New lead created
        - scheduled_touch: Time-based touch due
        """
        # Determine which Power Play applies based on lead stage/timeline
        workflow_type = self._determine_lead_workflow(lead)

        if workflow_type == PowerPlayType.PROSPECT:
            return self._execute_prospect_power_play(lead, trigger)
        elif workflow_type == PowerPlayType.PREQUAL:
            return self._execute_prequal_power_play(lead, trigger)
        elif workflow_type == PowerPlayType.PRE_APPROVED:
            return self._execute_pre_approved_power_play(lead, trigger)
        elif workflow_type == PowerPlayType.LONG_TERM_NURTURE:
            return self._execute_long_term_nurture_power_play(lead, trigger)
        else:
            return PowerPlayResult(
                workflow_type=PowerPlayType.PROSPECT,
                entity_id=lead.id,
                entity_type="lead",
                status="no_workflow",
                message="No applicable Power Play for current lead stage"
            )

    def process_loan_workflow(self, loan: Any, trigger: str = None) -> PowerPlayResult:
        """Execute Under Contract Power Play for active loans"""
        return self._execute_under_contract_power_play(loan, trigger)

    def process_referral_workflow(self, entity: Any, entity_type: str, trigger: str = None) -> PowerPlayResult:
        """Execute referral-related Power Plays"""
        if entity_type == "past_client":
            return self._execute_consumer_referral_power_play(entity, trigger)
        elif entity_type == "referral_partner":
            return self._execute_circle_of_cash_flow_power_play(entity, trigger)
        else:
            return PowerPlayResult(
                workflow_type=PowerPlayType.CONSUMER_REFERRAL,
                entity_id=entity.id,
                entity_type=entity_type,
                status="invalid_type",
                message=f"Unknown entity type: {entity_type}"
            )

    # ==========================================================================
    # WORKFLOW TYPE DETERMINATION
    # ==========================================================================

    def _determine_lead_workflow(self, lead: Any) -> Optional[PowerPlayType]:
        """Determine which Power Play applies based on lead characteristics"""
        stage = str(lead.stage.value) if hasattr(lead.stage, 'value') else str(lead.stage)
        timeline = getattr(lead, 'buying_timeline_category', None)

        # Check stage first
        if stage in ["Pre-Approved", "PreApproved"]:
            return PowerPlayType.PRE_APPROVED

        # Check timeline category
        if timeline:
            timeline_val = timeline.value if hasattr(timeline, 'value') else str(timeline)
            if timeline_val == "Green":  # 10+ months
                return PowerPlayType.LONG_TERM_NURTURE

        # PreQual check - has soft credit pull but not pre-approved
        if stage in ["Application Complete", "Application Started"]:
            return PowerPlayType.PREQUAL

        # Default to Prospect for active buyers
        if stage in ["New", "Attempted Contact", "Prospect"]:
            return PowerPlayType.PROSPECT

        return None

    # ==========================================================================
    # 1. PROSPECT POWER PLAY
    # ==========================================================================

    def _execute_prospect_power_play(self, lead: Any, trigger: str) -> PowerPlayResult:
        """
        Prospect Power Play - Active buyers with 10-month timeline

        Timeline-Based Touch Frequency:
        - Platinum (< 3 mo): Every 7 days
        - Gold (4-6 mo): Every 14 days
        - Silver (7-9 mo): Every 21 days
        - Green (10+ mo): Route to Long-Term Nurture
        """
        actions = []
        first_name = lead.name.split()[0] if lead.name else "there"

        # Determine touch frequency based on timeline
        timeline = getattr(lead, 'buying_timeline_category', None)
        timeline_val = timeline.value if timeline and hasattr(timeline, 'value') else "Silver"

        touch_days = {
            "Platinum": self.touch_frequency.platinum,
            "Gold": self.touch_frequency.gold,
            "Silver": self.touch_frequency.silver,
            "Green": self.touch_frequency.green
        }.get(timeline_val, 14)

        # Route to Long-Term Nurture if Green
        if timeline_val == "Green":
            return self._execute_long_term_nurture_power_play(lead, trigger)

        # Schedule next touch
        next_touch = datetime.now(timezone.utc) + timedelta(days=touch_days)

        if trigger == "new_lead":
            # New prospect actions
            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.TASK,
                target="loan_officer",
                data={
                    "title": f"Initial Discovery Call with {first_name}",
                    "description": "Complete needs analysis: timeline, budget, loan type preference, concerns",
                    "due_hours": 24,
                    "priority": "high",
                    "lead_id": lead.id
                },
                priority="high"
            ))

            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.TAG,
                target="lead",
                data={
                    "lead_id": lead.id,
                    "tags": [f"timeline:{timeline_val.lower()}", "prospect_power_play"]
                }
            ))

            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.DRIP_CAMPAIGN,
                target="lead",
                data={
                    "lead_id": lead.id,
                    "campaign": f"prospect_nurture_{timeline_val.lower()}",
                    "start_immediately": True
                }
            ))

        elif trigger == "scheduled_touch":
            # Scheduled touch-point
            touch_type = self._get_varied_touch_type(lead)

            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.TASK,
                target="loan_officer",
                data={
                    "title": f"{touch_type} touch with {first_name}",
                    "description": f"Scheduled {timeline_val} timeline touch. Check for timeline changes, address concerns.",
                    "due_hours": touch_days * 24,
                    "priority": "medium",
                    "lead_id": lead.id
                }
            ))

        elif trigger == "timeline_update":
            # Timeline changed - adjust workflow
            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.ALERT,
                target="loan_officer",
                data={
                    "message": f"Timeline updated for {first_name}: now {timeline_val}",
                    "lead_id": lead.id
                }
            ))

            # Update drip campaign
            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.DRIP_CAMPAIGN,
                target="lead",
                data={
                    "lead_id": lead.id,
                    "campaign": f"prospect_nurture_{timeline_val.lower()}",
                    "stop_previous": True
                }
            ))

        return PowerPlayResult(
            workflow_type=PowerPlayType.PROSPECT,
            entity_id=lead.id,
            entity_type="lead",
            actions=actions,
            next_touch_date=next_touch,
            status="processed",
            message=f"Prospect Power Play: {len(actions)} actions, next touch in {touch_days} days"
        )


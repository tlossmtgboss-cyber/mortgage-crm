    async def run_scheduled_touches(self) -> List[PowerPlayResult]:
        """Run all scheduled touches that are due"""
        results = []
        now = datetime.now(timezone.utc)

        # Find leads with due touches
        try:
            due_leads = self.db.execute(text("""
                SELECT id, name, email, phone, stage, owner_id,
                       buying_timeline_category, next_touch_date
                FROM leads
                WHERE next_touch_date <= :now
                AND stage NOT IN ('Closed', 'Dead')
            """), {"now": now})

            for lead_row in due_leads.fetchall():
                # Create a simple lead object
                class LeadObj:
                    pass
                lead = LeadObj()
                lead.id = lead_row.id
                lead.name = lead_row.name
                lead.email = lead_row.email
                lead.phone = lead_row.phone
                lead.stage = lead_row.stage
                lead.owner_id = lead_row.owner_id
                lead.buying_timeline_category = lead_row.buying_timeline_category

                result = self.engine.process_lead_workflow(lead, trigger="scheduled_touch")
                results.append(result)

                # Update next touch date
                if result.next_touch_date:
                    self.db.execute(text("""
                        UPDATE leads SET next_touch_date = :next_touch
                        WHERE id = :lead_id
                    """), {"next_touch": result.next_touch_date, "lead_id": lead.id})

            self.db.commit()

        except Exception as e:
            logger.error(f"Error running scheduled touches: {e}")
            self.db.rollback()

        return results


    # ==========================================================================
    # 5. UNDER CONTRACT POWER PLAY
    # ==========================================================================

    def _execute_under_contract_power_play(self, loan: Any, trigger: str) -> PowerPlayResult:
        """
        Under Contract Power Play - Active loan management

        Rate Lock Intelligence integration, milestone management
        """
        actions = []
        borrower_name = (loan.borrower_name or "Borrower").strip() or "Borrower"
        first_name = borrower_name.split()[0]

        if trigger == "new_contract":
            # New under-contract loan
            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.TASK,
                target="loan_officer",
                data={
                    "title": f"Lock decision for {first_name}",
                    "description": "Review Rate Lock Intelligence recommendation. Discuss lock strategy with borrower.",
                    "due_hours": 4,
                    "priority": "urgent",
                    "loan_id": loan.id
                },
                priority="urgent"
            ))

            # Initial Rate Lock check
            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.RATE_LOCK_CHECK,
                target="loan",
                data={
                    "loan_id": loan.id,
                    "trigger": "under_contract",
                    "analyze_immediately": True
                }
            ))

            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.EMAIL,
                target="borrower",
                data={
                    "to": getattr(loan, 'borrower_email', None),
                    "subject": f"Your Loan is In Progress, {first_name}!",
                    "template": "loan_in_progress",
                    "borrower_name": borrower_name,
                    "loan_number": loan.loan_number
                }
            ))

        elif trigger == "milestone_reached":
            # Milestone automation
            stage = str(loan.stage.value) if hasattr(loan.stage, 'value') else str(loan.stage)

            milestone_tasks = self._get_milestone_tasks(loan, stage)
            actions.extend(milestone_tasks)

            # Notify borrower of milestone
            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.EMAIL,
                target="borrower",
                data={
                    "to": getattr(loan, 'borrower_email', None),
                    "subject": f"Great News! Your Loan Reached {stage}",
                    "template": f"milestone_{stage.lower().replace(' ', '_')}",
                    "borrower_name": borrower_name
                }
            ))

        elif trigger == "rate_lock_expiring":
            # Rate lock expiration warning
            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.ALERT,
                target="loan_officer",
                data={
                    "message": f"URGENT: Rate lock expiring for {first_name}'s loan!",
                    "loan_id": loan.id,
                    "priority": "critical"
                },
                priority="urgent"
            ))

            actions.append(PowerPlayAction(
                action_type=WorkflowActionType.TASK,
                target="loan_officer",
                data={
                    "title": f"Rate lock extension decision for {first_name}",
                    "description": "Lock expiring soon. Review extension costs vs relock options.",
                    "due_hours": 24,
                    "priority": "urgent",
                    "loan_id": loan.id
                },
                priority="urgent"
            ))

        elif trigger == "closing_approaching":
            # Closing countdown
            days_to_close = self._calculate_days_to_close(loan)

            if days_to_close <= 7:
                actions.append(PowerPlayAction(
                    action_type=WorkflowActionType.TASK,
                    target="loan_officer",
                    data={
                        "title": f"Final closing prep for {first_name}",
                        "description": f"Closing in {days_to_close} days. Verify all conditions cleared, CD sent, wire instructions ready.",
                        "due_hours": 24,
                        "priority": "high",
                        "loan_id": loan.id
                    },
                    priority="high"
                ))

                actions.append(PowerPlayAction(
                    action_type=WorkflowActionType.EMAIL,
                    target="borrower",
                    data={
                        "to": getattr(loan, 'borrower_email', None),
                        "subject": f"Closing Week! What to Expect, {first_name}",
                        "template": "closing_week_prep",
                        "borrower_name": borrower_name,
                        "days_to_close": days_to_close
                    }
                ))

        return PowerPlayResult(
            workflow_type=PowerPlayType.UNDER_CONTRACT,
            entity_id=loan.id,
            entity_type="loan",
            actions=actions,
            status="processed",
            message=f"Under Contract Power Play: {len(actions)} actions"
        )


    def _calculate_days_to_close(self, loan: Any) -> int:
        """Calculate days until closing"""
        closing_date = getattr(loan, 'estimated_closing_date', None)
        if closing_date:
            if isinstance(closing_date, datetime):
                delta = closing_date - datetime.now(timezone.utc)
            else:
                delta = datetime.combine(closing_date, datetime.min.time()) - datetime.now()
            return max(0, delta.days)
        return 30  # Default assumption



class AccessCodeService:
    """Manages 6-digit access codes issued by LOs for borrower portal login."""

    @staticmethod
    def generate_access_code(
        borrower_email: str,
        loan_id: Any,
        org_id: Any,
        expires_minutes: int = ACCESS_CODE_EXPIRY_MINUTES,
    ) -> str:
        """
        Generate a 6-digit access code for a borrower.

        The LO provides this code to the borrower (via phone, text, etc.)
        who then enters it on the portal login screen.

        Args:
            borrower_email: Borrower's email.
            loan_id: Associated loan ID.
            org_id: Organization ID.
            expires_minutes: Code expiry in minutes.

        Returns:
            6-digit access code string.
        """
        email_lower = borrower_email.strip().lower()
        code = "".join([str(secrets.randbelow(10)) for _ in range(ACCESS_CODE_LENGTH)])
        expires_at = datetime.now(timezone.utc) + timedelta(minutes=expires_minutes)

        _access_codes[email_lower] = {
            "code": code,
            "loan_id": str(loan_id),
            "org_id": str(org_id),
            "expires_at": expires_at,
            "attempts": 0,
            "max_attempts": 5,
            "created_at": datetime.now(timezone.utc),
        }

        logger.info(
            f"Access code generated for {_mask_email(email_lower)}, "
            f"loan={loan_id}, expires={expires_at.isoformat()}"
        )
        return code

    @staticmethod
    def verify_access_code(
        borrower_email: str,
        code: str,
    ) -> Dict[str, Any]:
        """
        Verify a 6-digit access code.

        Args:
            borrower_email: Borrower's email.
            code: The 6-digit code to verify.

        Returns:
            Dict with loan_id and org_id on success.

        Raises:
            ValueError: If code is invalid, expired, or max attempts exceeded.
        """
        email_lower = borrower_email.strip().lower()

        stored = _access_codes.get(email_lower)
        if not stored:
            raise ValueError("No access code found. Please request a new code from your loan officer.")

        # Check expiry
        if datetime.now(timezone.utc) > stored["expires_at"]:
            del _access_codes[email_lower]
            raise ValueError("Access code has expired. Please request a new code from your loan officer.")

        # Check max attempts
        stored["attempts"] += 1
        if stored["attempts"] > stored["max_attempts"]:
            del _access_codes[email_lower]
            raise ValueError("Too many incorrect attempts. Please request a new code.")

        # Constant-time comparison to prevent timing attacks
        if not secrets.compare_digest(code.strip(), stored["code"]):
            remaining = stored["max_attempts"] - stored["attempts"]
            raise ValueError(f"Invalid access code. {remaining} attempts remaining.")

        # Code is valid - consume it (single-use)
        result = {
            "loan_id": stored["loan_id"],
            "org_id": stored["org_id"],
        }
        del _access_codes[email_lower]
        return result



class PortalV2TokenService:
    """Handles JWT token generation and verification for portal V2 sessions."""

    @staticmethod
    def generate_token(
        loan_id: Any,
        borrower_email: str,
        org_id: Any,
        scope: str = "read_write",
        expires_hours: int = PORTAL_V2_TOKEN_EXPIRY_HOURS,
    ) -> str:
        """
        Generate a signed JWT portal session token.

        Args:
            loan_id: Loan ID the borrower is authorized to access.
            borrower_email: Borrower's email address.
            org_id: Organization ID for tenant isolation.
            scope: "read" or "read_write".
            expires_hours: Token lifetime in hours (default 24).

        Returns:
            Signed JWT string.

        Raises:
            ValueError: If required parameters are missing.
        """
        if not loan_id or not borrower_email or not org_id:
            raise ValueError("loan_id, borrower_email, and org_id are required")

        email_lower = borrower_email.strip().lower()
        now = datetime.now(timezone.utc)
        expires_at = now + timedelta(hours=expires_hours)

        payload = {
            "iss": PORTAL_V2_ISSUER,
            "sub": email_lower,
            "loan_id": str(loan_id),
            "org_id": str(org_id),
            "scope": scope,
            "version": "v2",
            "jti": str(uuid.uuid4()),
            "iat": int(now.timestamp()),
            "exp": int(expires_at.timestamp()),
        }

        token = jwt.encode(payload, SECRET_KEY, algorithm=PORTAL_V2_ALGORITHM)
        logger.info(
            f"Portal V2 token generated for {_mask_email(email_lower)}, "
            f"loan={loan_id}, org={org_id}, expires={expires_at.isoformat()}"
        )
        return token

    @staticmethod
    def verify_token(token: str) -> Dict[str, Any]:
        """
        Verify a portal V2 token and return decoded claims.

        Returns:
            Dict with loan_id, borrower_email, org_id, scope, issued_at, expires_at.

        Raises:
            ValueError: If the token is invalid, expired, or malformed.
        """
        if not token:
            raise ValueError("Portal access token is required")

        try:
            payload = jwt.decode(
                token,
                SECRET_KEY,
                algorithms=[PORTAL_V2_ALGORITHM],
                issuer=PORTAL_V2_ISSUER,
                options={"require": ["exp", "iss", "sub", "loan_id", "org_id"]},
            )
        except jwt.ExpiredSignatureError:
            raise ValueError("Portal session has expired. Please request a new link.")
        except jwt.InvalidIssuerError:
            raise ValueError("Invalid portal token")
        except jwt.DecodeError:
            raise ValueError("Invalid portal token")
        except jwt.MissingRequiredClaimError:
            raise ValueError("Invalid portal token")
        except jwt.InvalidTokenError:
            raise ValueError("Invalid portal token")

        return {
            "loan_id": payload["loan_id"],
            "borrower_email": payload["sub"],
            "org_id": payload["org_id"],
            "scope": payload.get("scope", "read"),
            "jti": payload.get("jti"),
            "issued_at": datetime.fromtimestamp(payload["iat"], tz=timezone.utc).isoformat(),
            "expires_at": datetime.fromtimestamp(payload["exp"], tz=timezone.utc).isoformat(),
        }



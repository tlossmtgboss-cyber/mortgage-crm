    async def process_upload(
        self,
        file_bytes: bytes,
        filename: str,
        content_type: str,
        loan_id: str,
        org_id: str,
        borrower_email: str,
        request_id: Optional[int] = None,
        doc_type_hint: Optional[str] = None,
        upload_source: str = "WEB",
        camera_capture: bool = False,
        lang: str = "en",
    ) -> Dict[str, Any]:
        """
        Process a document upload from the borrower portal.

        Validates the file, stores it, queues for AI classification and review,
        and returns upload confirmation with next-steps guidance.

        Args:
            file_bytes: Raw file content.
            filename: Original filename.
            content_type: MIME type.
            loan_id: Loan ID.
            org_id: Organization ID.
            borrower_email: Uploading borrower's email.
            request_id: Optional document request ID this fulfills.
            doc_type_hint: Optional document type hint from borrower.
            upload_source: "WEB", "MOBILE", or "EMAIL".
            camera_capture: Whether this was captured via camera (mobile).
            lang: Language code.

        Returns:
            Dict with upload confirmation, document_id, next steps.

        Raises:
            ValueError: If validation fails or rate limited.
        """
        # Rate limit
        self.rate_limiter.check_upload_rate_limit(borrower_email)

        # Validate
        validation = self.upload_validator.validate_upload(
            filename=filename,
            content_type=content_type,
            file_size=len(file_bytes),
        )

        # Quality assessment for images
        quality = self.upload_validator.assess_image_quality(file_bytes, content_type)

        # Compute file hash
        file_hash = hashlib.sha256(file_bytes).hexdigest()

        # Check for duplicate upload on this loan
        duplicate_check = self.db.execute(
            sa_text("""
                SELECT id, file_name, uploaded_at
                FROM smart_documents
                WHERE loan_id = :loan_id
                    AND storage_key LIKE :hash_pattern
                    AND status NOT IN ('DELETED', 'SUPERSEDED')
                LIMIT 1
            """),
            {"loan_id": int(loan_id), "hash_pattern": f"%{file_hash[:16]}%"},
        ).fetchone()

        is_duplicate = duplicate_check is not None

        # Attempt AI classification if no type hint provided
        classification_result = None
        if not doc_type_hint:
            try:
                from services.smart_docs.ai_classifier_service import get_ai_classifier_service
                classifier = get_ai_classifier_service()
                classification_result = classifier.classify_document(
                    file_bytes, content_type, filename
                )
                if classification_result and classification_result.confidence >= 70:
                    doc_type_hint = classification_result.predicted_type
            except Exception as e:
                logger.warning(f"AI classification failed during upload, continuing: {e}")

        # Store document via upload pipeline
        storage_key = f"smart-docs/{org_id}/{loan_id}/{file_hash[:16]}_{filename}"

        try:
            from services.smart_docs.s3_storage_service import get_smart_docs_s3_service
            s3 = get_smart_docs_s3_service()
            s3.upload_file(
                file_data=file_bytes,
                storage_key=storage_key,
                content_type=content_type,
                metadata={
                    "loan_id": str(loan_id),
                    "org_id": str(org_id),
                    "borrower_email": borrower_email,
                    "upload_source": upload_source,
                    "camera_capture": str(camera_capture),
                },
            )
        except Exception as e:
            logger.error(f"S3 upload failed for loan {loan_id}: {e}")
            raise ValueError("Document upload failed. Please try again.")

        # Resolve borrower_id from email
        borrower_id_row = self.db.execute(
            sa_text("""
                SELECT id FROM borrower_profiles
                WHERE email = :email
                LIMIT 1
            """),
            {"email": borrower_email.strip().lower()},
        ).fetchone()
        borrower_id = borrower_id_row[0] if borrower_id_row else 0

        # Insert SmartDocument record
        now_ts = datetime.now(timezone.utc)
        insert_result = self.db.execute(
            sa_text("""
                INSERT INTO smart_documents (
                    request_id, loan_id, borrower_id, file_name, original_filename,
                    mime_type, file_size, storage_key, doc_type, detected_doc_type,
                    status, upload_source, uploaded_at, created_at, updated_at
                ) VALUES (
                    :request_id, :loan_id, :borrower_id, :file_name, :original_filename,
                    :mime_type, :file_size, :storage_key, :doc_type, :detected_doc_type,
                    'UPLOADED', :upload_source, :uploaded_at, :created_at, :updated_at
                ) RETURNING id
            """),
            {
                "request_id": request_id,
                "loan_id": int(loan_id),
                "borrower_id": borrower_id,
                "file_name": filename,
                "original_filename": filename,
                "mime_type": content_type,
                "file_size": len(file_bytes),
                "storage_key": storage_key,
                "doc_type": doc_type_hint,
                "detected_doc_type": (
                    classification_result.predicted_type if classification_result else None
                ),
                "upload_source": upload_source,
                "uploaded_at": now_ts,
                "created_at": now_ts,
                "updated_at": now_ts,
            },
        )
        doc_id = insert_result.fetchone()[0]
        self.db.commit()

        # If fulfilling a specific request, update its status
        if request_id:
            self.db.execute(
                sa_text("""
                    UPDATE smart_document_requests
                    SET status = 'PENDING_REVIEW', updated_at = :now
                    WHERE id = :request_id AND status = 'OPEN'
                """),
                {"request_id": request_id, "now": now_ts},
            )
            self.db.commit()

        # Log analytics event
        await self._log_portal_event(
            loan_id=loan_id,
            org_id=org_id,
            event_type="document_uploaded",
            borrower_email=borrower_email,
            metadata={
                "document_id": doc_id,
                "doc_type": doc_type_hint,
                "file_size": len(file_bytes),
                "upload_source": upload_source,
                "camera_capture": camera_capture,
                "is_duplicate": is_duplicate,
            },
        )

        return {
            "success": True,
            "document_id": doc_id,
            "filename": filename,
            "file_size": validation["file_size_display"],
            "doc_type": doc_type_hint,
            "classification": {
                "predicted_type": classification_result.predicted_type if classification_result else None,
                "confidence": classification_result.confidence if classification_result else None,
            } if classification_result else None,
            "quality": quality,
            "is_duplicate": is_duplicate,
            "status": "UPLOADED",
            "message": _get_translation("upload_success", lang),
            "next_steps": _get_translation("upload_next_steps", lang),
            "upload_metadata": {
                "source": upload_source,
                "camera_capture": camera_capture,
                "timestamp": now_ts.isoformat(),
            },
        }


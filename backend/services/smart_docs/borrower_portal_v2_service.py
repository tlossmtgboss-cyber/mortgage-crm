class UploadValidator:
    """Validates document uploads for portal V2."""

    @staticmethod
    def validate_upload(
        filename: str,
        content_type: str,
        file_size: int,
    ) -> Dict[str, Any]:
        """
        Validate an upload file for type, size, and extension.

        Args:
            filename: Original filename.
            content_type: MIME type of the upload.
            file_size: Size in bytes.

        Returns:
            Dict with validation result and details.

        Raises:
            ValueError: If validation fails.
        """
        issues = []

        # Extension check
        ext = ""
        if "." in filename:
            ext = "." + filename.rsplit(".", 1)[-1].lower()
        if ext not in ALLOWED_EXTENSIONS:
            issues.append(
                f"File type '{ext or 'unknown'}' is not supported. "
                f"Accepted: PDF, JPG, PNG, TIFF, HEIC"
            )

        # MIME type check
        if content_type and content_type.lower() not in ALLOWED_MIME_TYPES:
            issues.append(
                f"Content type '{content_type}' is not supported."
            )

        # Size check
        if file_size > MAX_FILE_SIZE_BYTES:
            issues.append(
                f"File is too large ({file_size / (1024 * 1024):.1f} MB). "
                f"Maximum size is {MAX_FILE_SIZE_MB} MB."
            )

        if file_size == 0:
            issues.append("File is empty.")

        if issues:
            raise ValueError(" ".join(issues))

        return {
            "valid": True,
            "filename": filename,
            "extension": ext,
            "content_type": content_type,
            "file_size": file_size,
            "file_size_display": f"{file_size / (1024 * 1024):.2f} MB" if file_size >= 1024 * 1024 else f"{file_size / 1024:.1f} KB",
        }

    @staticmethod
    def assess_image_quality(file_bytes: bytes, content_type: str) -> Dict[str, Any]:
        """
        Assess image quality for readability (basic heuristic checks).

        For images, checks minimum resolution threshold via file size.
        Full OCR quality analysis happens downstream in the AI review pipeline.

        Returns:
            Dict with quality assessment.
        """
        quality = {
            "acceptable": True,
            "warnings": [],
        }

        if content_type and content_type.startswith("image/"):
            # Very small images are likely too low resolution
            if len(file_bytes) < 50_000:  # < 50KB
                quality["warnings"].append(
                    "Image appears to be low resolution. Please ensure the document is clearly readable."
                )
            # Very large uncompressed images might be photos of screens
            if len(file_bytes) > 15_000_000:  # > 15MB
                quality["warnings"].append(
                    "Image is very large. Consider taking a clearer, cropped photo."
                )

        return quality



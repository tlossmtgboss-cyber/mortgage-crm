    async def _verify_borrower_on_loan(
        self,
        borrower_email: str,
        loan_id: int,
        org_id: int,
    ) -> Dict[str, Any]:
        """
        Verify that a borrower email is associated with a loan in the org.

        Checks the loan's borrower_email and co_borrower_email fields.

        Raises:
            ValueError: If borrower not found on loan.
        """
        loan = self.db.execute(
            sa_text("""
                SELECT
                    l.borrower_name, l.borrower_email, l.co_borrower_email,
                    l.coborrower_name
                FROM loans l
                WHERE l.id = :loan_id AND l.organization_id = :org_id
            """),
            {"loan_id": loan_id, "org_id": org_id},
        ).fetchone()

        if not loan:
            raise ValueError("Loan not found")

        # Check if email matches borrower or co-borrower
        loan_borrower_email = (loan[1] or "").strip().lower()
        loan_coborrower_email = (loan[2] or "").strip().lower()
        email_lower = borrower_email.strip().lower()

        if email_lower == loan_borrower_email:
            return {"name": loan[0] or "", "role": "borrower"}
        elif email_lower == loan_coborrower_email:
            return {"name": loan[3] or "", "role": "co_borrower"}
        else:
            raise ValueError("Email not associated with this loan")

    async def _get_recent_activities(
        self,
        loan_id: str,
        limit: int = 10,
    ) -> List[Dict[str, Any]]:
        """Get recent activities for a loan (borrower-safe info only)."""
        try:
            activities = self.db.execute(
                sa_text("""
                    SELECT type, content, created_at
                    FROM activities
                    WHERE loan_id = :loan_id
                    ORDER BY created_at DESC
                    LIMIT :limit
                """),
                {"loan_id": int(loan_id), "limit": limit},
            ).fetchall()

            return [
                {
                    "type": row[0],
                    "description": (row[1] or "")[:200],
                    "date": row[2].isoformat() if row[2] else None,
                }
                for row in activities
            ]
        except Exception as e:
            logger.warning(f"Failed to fetch activities for loan {loan_id}: {e}")
            return []


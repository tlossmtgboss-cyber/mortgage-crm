def _mask_email(email: str) -> str:
    """Mask email for logging (e.g., j***n@example.com)."""
    parts = email.split("@")
    if len(parts) != 2:
        return "***"
    local = parts[0]
    domain = parts[1]
    if len(local) <= 2:
        masked = local[0] + "***"
    else:
        masked = local[0] + "***" + local[-1]
    return f"{masked}@{domain}"


def _get_translation(key: str, lang: str = "en") -> str:
    """Get translated string, falling back to English."""
    translations = _TRANSLATIONS.get(lang, _TRANSLATIONS["en"])
    return translations.get(key, _TRANSLATIONS["en"].get(key, key))



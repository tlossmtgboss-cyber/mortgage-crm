class BorrowerPortalV2Service:
    """
    Core service for the borrower document portal V2.

    Coordinates authentication, document management, messaging, e-signatures,
    progress tracking, and analytics for the borrower-facing portal.
    """

    def __init__(self, db: Session):
        self.db = db
        self.token_service = PortalV2TokenService()
        self.rate_limiter = PortalRateLimiter()
        self.access_code_service = AccessCodeService()
        self.upload_validator = UploadValidator()

    # -----------------------------------------------------------------------
    # Authentication
    # -----------------------------------------------------------------------

    async def send_magic_link(
        self,
        borrower_email: str,
        loan_id: int,
        org_id: int,
        lang: str = "en",
    ) -> Dict[str, Any]:
        """
        Send a magic link to the borrower's email for portal access.

        Validates the borrower exists on the loan, generates a 24-hour token,
        and constructs the magic link URL.  Email delivery is delegated to
        the caller (routes layer) since the email service is async.

        Args:
            borrower_email: Borrower's email address.
            loan_id: The loan to grant access to.
            org_id: Organization ID for tenant isolation.
            lang: Language code ("en" or "es").

        Returns:
            Dict with magic_link_url, token, expires_at, email_subject, email_body.

        Raises:
            ValueError: If rate limited or borrower not found.
        """
        email_lower = borrower_email.strip().lower()

        # Rate limit
        self.rate_limiter.check_login_rate_limit(email_lower)

        # Verify borrower exists on this loan in this org
        borrower_info = await self._verify_borrower_on_loan(email_lower, loan_id, org_id)

        # Generate token
        token = self.token_service.generate_token(
            loan_id=loan_id,
            borrower_email=email_lower,
            org_id=org_id,
            scope="read_write",
        )

        # Build magic link URL
        magic_link_url = f"{PORTAL_BASE_URL}/v2/auth?token={token}"

        # Get branding
        branding = await self._get_org_branding(org_id)

        # Build email content
        subject = _get_translation("magic_link_subject", lang)
        body = _get_translation("magic_link_body", lang)

        claims = self.token_service.verify_token(token)

        return {
            "magic_link_url": magic_link_url,
            "token": token,
            "expires_at": claims["expires_at"],
            "borrower_name": borrower_info.get("name", ""),
            "email_subject": subject,
            "email_body": body,
            "branding": branding,
            "lang": lang,
        }

    async def verify_auth(
        self,
        email: Optional[str] = None,
        token: Optional[str] = None,
        access_code: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Verify portal authentication via magic link token or access code.

        Exactly one of token or access_code must be provided.

        Args:
            email: Borrower email (required for access_code auth).
            token: JWT token from magic link.
            access_code: 6-digit access code from LO.

        Returns:
            Dict with session_token, borrower_email, loan_id, org_id, expires_at.

        Raises:
            ValueError: If authentication fails.
        """
        if token:
            # Magic link verification
            claims = self.token_service.verify_token(token)
            # Token is already a valid session token
            return {
                "session_token": token,
                "borrower_email": claims["borrower_email"],
                "loan_id": claims["loan_id"],
                "org_id": claims["org_id"],
                "scope": claims["scope"],
                "expires_at": claims["expires_at"],
                "auth_method": "magic_link",
            }

        elif access_code and email:
            email_lower = email.strip().lower()

            # Rate limit
            self.rate_limiter.check_login_rate_limit(email_lower)

            # Verify access code
            code_claims = self.access_code_service.verify_access_code(email_lower, access_code)

            # Generate a fresh session token
            session_token = self.token_service.generate_token(
                loan_id=code_claims["loan_id"],
                borrower_email=email_lower,
                org_id=code_claims["org_id"],
                scope="read_write",
            )

            token_claims = self.token_service.verify_token(session_token)

            return {
                "session_token": session_token,
                "borrower_email": email_lower,
                "loan_id": code_claims["loan_id"],
                "org_id": code_claims["org_id"],
                "scope": "read_write",
                "expires_at": token_claims["expires_at"],
                "auth_method": "access_code",
            }

        else:
            raise ValueError("Either token or (email + access_code) is required for authentication.")

    # -----------------------------------------------------------------------
    # Document Checklist
    # -----------------------------------------------------------------------

    async def get_checklist(
        self,
        loan_id: str,
        org_id: str,
        lang: str = "en",
    ) -> Dict[str, Any]:
        """
        Get the document checklist for a loan, grouped by category.

        Returns outstanding items with priority, completed items with timestamps,
        due dates, overdue warnings, and category grouping.

        Args:
            loan_id: Loan ID.
            org_id: Organization ID for tenant isolation.
            lang: Language code.

        Returns:
            Dict with categories, summary stats, and individual items.
        """
        # Fetch all active document requests for this loan
        requests_rows = self.db.execute(
            sa_text("""
                SELECT
                    sdr.id, sdr.doc_type, sdr.title, sdr.description,
                    sdr.instructions, sdr.priority, sdr.status,
                    sdr.due_date, sdr.completed_at, sdr.required_count,
                    sdr.created_at
                FROM smart_document_requests sdr
                JOIN loans l ON l.id = sdr.loan_id
                WHERE sdr.loan_id = :loan_id
                    AND l.organization_id = :org_id
                    AND sdr.is_active = true
                ORDER BY
                    CASE sdr.priority
                        WHEN 'CRITICAL' THEN 1
                        WHEN 'HIGH' THEN 2
                        WHEN 'NORMAL' THEN 3
                        WHEN 'LOW' THEN 4
                        ELSE 5
                    END,
                    sdr.created_at ASC
            """),
            {"loan_id": int(loan_id), "org_id": int(org_id)},
        ).fetchall()

        # Fetch uploaded documents grouped by request_id
        uploaded_rows = self.db.execute(
            sa_text("""
                SELECT
                    sd.id, sd.request_id, sd.file_name, sd.display_name,
                    sd.status, sd.decision, sd.uploaded_at,
                    sd.rejection_reason, sd.fix_instructions,
                    sd.detected_doc_type, sd.doc_type
                FROM smart_documents sd
                WHERE sd.loan_id = :loan_id
                    AND sd.status NOT IN ('DELETED', 'SUPERSEDED')
                ORDER BY sd.uploaded_at DESC
            """),
            {"loan_id": int(loan_id)},
        ).fetchall()

        # Index uploaded docs by request_id
        docs_by_request: Dict[int, List[Dict]] = defaultdict(list)
        for row in uploaded_rows:
            docs_by_request[row[1]].append({
                "document_id": row[0],
                "request_id": row[1],
                "file_name": row[3] or row[2],  # display_name or file_name
                "status": row[4],
                "decision": row[5],
                "uploaded_at": row[6].isoformat() if row[6] else None,
                "rejection_reason": row[7],
                "fix_instructions": row[8],
            })

        # Build categorized checklist
        categories: Dict[str, List[Dict]] = defaultdict(list)
        total_items = 0
        completed_items = 0
        overdue_items = 0
        now = datetime.now(timezone.utc)

        for req_row in requests_rows:
            req_id = req_row[0]
            doc_type = req_row[1]
            status = req_row[6]
            due_date = req_row[7]
            completed_at = req_row[8]

            # Determine category
            doc_type_str = doc_type.value if hasattr(doc_type, "value") else str(doc_type) if doc_type else "OTHER"
            category_key = _DOC_TYPE_CATEGORIES.get(doc_type_str, "special")
            category_label = _get_translation(f"category_{category_key}", lang)

            # Check overdue
            is_overdue = False
            if due_date and status not in ("ACCEPTED", "WAIVED") and due_date < now:
                is_overdue = True
                overdue_items += 1

            # Check completion
            is_completed = status in ("ACCEPTED", "WAIVED")
            if is_completed:
                completed_items += 1
            total_items += 1

            # Priority indicator for mobile
            priority_val = req_row[5]
            priority_str = priority_val.value if hasattr(priority_val, "value") else str(priority_val) if priority_val else "NORMAL"
            priority_indicators = {
                "CRITICAL": {"level": 1, "color": "#dc2626", "icon": "priority_high"},
                "HIGH": {"level": 2, "color": "#f59e0b", "icon": "arrow_upward"},
                "NORMAL": {"level": 3, "color": "#6b7280", "icon": "remove"},
                "LOW": {"level": 4, "color": "#9ca3af", "icon": "arrow_downward"},
            }

            item = {
                "request_id": req_id,
                "doc_type": doc_type_str,
                "title": req_row[2],
                "description": req_row[3],
                "instructions": req_row[4],
                "priority": priority_str,
                "priority_indicator": priority_indicators.get(priority_str, priority_indicators["NORMAL"]),
                "status": status.value if hasattr(status, "value") else str(status),
                "is_completed": is_completed,
                "is_overdue": is_overdue,
                "overdue_warning": _get_translation("overdue_warning", lang) if is_overdue else None,
                "due_date": due_date.isoformat() if due_date else None,
                "completed_at": completed_at.isoformat() if completed_at else None,
                "required_count": req_row[9] or 1,
                "uploaded_documents": docs_by_request.get(req_id, []),
                "uploaded_count": len(docs_by_request.get(req_id, [])),
            }
            categories[category_label].append(item)

        # Build response with mobile-friendly structure
        categories_list = []
        for cat_name, items in categories.items():
            cat_completed = sum(1 for i in items if i["is_completed"])
            categories_list.append({
                "name": cat_name,
                "items": items,
                "total_count": len(items),
                "completed_count": cat_completed,
                "progress_pct": round((cat_completed / len(items)) * 100) if items else 0,
            })

        # Sort categories: Income first, then Assets, Identity, Property, Credit, Special
        category_order = {
            _get_translation("category_income", lang): 0,
            _get_translation("category_assets", lang): 1,
            _get_translation("category_identity", lang): 2,
            _get_translation("category_property", lang): 3,
            _get_translation("category_credit", lang): 4,
            _get_translation("category_special", lang): 5,
        }
        categories_list.sort(key=lambda c: category_order.get(c["name"], 99))

        return {
            "title": _get_translation("checklist_title", lang),
            "loan_id": loan_id,
            "categories": categories_list,
            "summary": {
                "total_items": total_items,
                "completed_items": completed_items,
                "remaining_items": total_items - completed_items,
                "overdue_items": overdue_items,
                "completion_pct": round((completed_items / total_items) * 100) if total_items else 0,
            },
            "lang": lang,
        }


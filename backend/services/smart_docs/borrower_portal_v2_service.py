    # Loan Progress Tracker
    # -----------------------------------------------------------------------

    async def get_loan_progress(
        self,
        loan_id: str,
        org_id: str,
        lang: str = "en",
    ) -> Dict[str, Any]:
        """
        Get loan progress for the borrower portal, including pipeline stage,
        estimated closing date, and recent activity feed.

        Returns a mobile-friendly data structure with visual stage indicators.

        Args:
            loan_id: Loan ID.
            org_id: Organization ID.
            lang: Language code.

        Returns:
            Dict with stages, current_stage, estimated_close, activities.
        """
        loan = self.db.execute(
            sa_text("""
                SELECT
                    l.id, l.loan_number, l.borrower_name, l.stage,
                    l.closing_date, l.predicted_close_date,
                    l.property_address, l.amount, l.rate,
                    l.loan_type, l.loan_officer_name,
                    l.stage_changed_at, l.created_at
                FROM loans l
                WHERE l.id = :loan_id AND l.organization_id = :org_id
            """),
            {"loan_id": int(loan_id), "org_id": int(org_id)},
        ).fetchone()

        if not loan:
            raise ValueError("Loan not found")

        current_stage = loan[3] or "APPLICATION"

        # Build stage progress indicator
        stages = []
        current_found = False
        for stage_key, stage_label in _STAGE_DISPLAY_ORDER:
            is_current = (stage_key == current_stage)
            if is_current:
                current_found = True
            # CTC and CLEAR_TO_CLOSE are the same stage
            if stage_key == "CTC" and current_stage == "CLEAR_TO_CLOSE":
                is_current = True
                current_found = True

            status = "completed" if not current_found and not is_current else (
                "current" if is_current else "upcoming"
            )
            # If we hit current, everything before was completed
            stages.append({
                "key": stage_key,
                "label": stage_label,
                "status": status,
                "is_current": is_current,
            })

        # Fix: mark all stages before current as completed
        for i, stage in enumerate(stages):
            if stage["is_current"]:
                for j in range(i):
                    stages[j]["status"] = "completed"
                break

        # Terminal stages
        terminal_stages = ("FUNDED", "CANCELLED", "DENIED", "DEAD", "WITHDRAWN", "DOES_NOT_QUALIFY")
        if current_stage in terminal_stages and current_stage == "FUNDED":
            for stage in stages:
                stage["status"] = "completed"

        # Estimated closing date
        estimated_close = loan[4] or loan[5]  # closing_date or predicted_close_date
        days_to_close = None
        if estimated_close:
            if hasattr(estimated_close, "date"):
                close_date = estimated_close.date()
            else:
                close_date = estimated_close
            today = datetime.now(timezone.utc).date()
            days_to_close = (close_date - today).days
            if days_to_close < 0:
                days_to_close = None  # Past estimated close

        # Recent activity feed
        activities = await self._get_recent_activities(loan_id, limit=10)

        return {
            "title": _get_translation("progress_title", lang),
            "loan_id": loan_id,
            "loan_number": loan[1],
            "borrower_name": loan[2],
            "current_stage": current_stage,
            "current_stage_label": next(
                (s["label"] for s in stages if s["is_current"]), current_stage
            ),
            "stages": stages,
            "progress_pct": self._calculate_progress_pct(current_stage),
            "property_address": loan[6],
            "loan_amount": float(loan[7]) if loan[7] else None,
            "interest_rate": float(loan[8]) if loan[8] else None,
            "loan_type": loan[9],
            "loan_officer_name": loan[10],
            "estimated_closing_date": estimated_close.isoformat() if estimated_close else None,
            "days_to_close": days_to_close,
            "stage_entered_at": loan[11].isoformat() if loan[11] else None,
            "recent_activities": activities,
            "lang": lang,
        }


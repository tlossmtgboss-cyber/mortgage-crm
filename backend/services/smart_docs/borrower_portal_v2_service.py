    async def get_pending_signatures(
        self,
        loan_id: str,
        org_id: str,
        borrower_email: str,
        lang: str = "en",
    ) -> Dict[str, Any]:
        """
        Get pending e-signature envelopes for a borrower.

        Returns envelopes where the borrower is a recipient with pending status.

        Args:
            loan_id: Loan ID.
            org_id: Organization ID.
            borrower_email: Borrower's email.
            lang: Language code.

        Returns:
            Dict with pending signatures list.
        """
        email_lower = borrower_email.strip().lower()

        envelopes = self.db.execute(
            sa_text("""
                SELECT
                    e.id, e.envelope_uuid, e.title, e.status AS envelope_status,
                    e.created_at, e.expires_at, e.document_name,
                    r.id AS recipient_id, r.status AS recipient_status,
                    r.signing_url, r.viewed_at, r.signed_at, r.auth_method
                FROM esignature_envelopes e
                JOIN esignature_recipients r
                    ON r.envelope_id = e.id
                WHERE e.loan_id = :loan_id
                    AND e.organization_id = :org_id
                    AND r.email = :email
                    AND e.status NOT IN ('voided', 'expired', 'completed')
                    AND r.status NOT IN ('signed', 'declined')
                ORDER BY e.created_at DESC
            """),
            {
                "loan_id": int(loan_id),
                "org_id": int(org_id),
                "email": email_lower,
            },
        ).fetchall()

        pending_list = []
        for row in envelopes:
            is_urgent = False
            if row[5]:  # expires_at
                days_until_expiry = (row[5] - datetime.now(timezone.utc)).days
                is_urgent = days_until_expiry <= 3

            pending_list.append({
                "envelope_id": row[0],
                "envelope_uuid": row[1],
                "title": row[2],
                "envelope_status": row[3],
                "document_name": row[6],
                "recipient_id": row[7],
                "recipient_status": row[8],
                "signing_url": row[9],
                "viewed_at": row[10].isoformat() if row[10] else None,
                "signed_at": row[11].isoformat() if row[11] else None,
                "auth_method": row[12],
                "created_at": row[4].isoformat() if row[4] else None,
                "expires_at": row[5].isoformat() if row[5] else None,
                "is_urgent": is_urgent,
                "action_label": _get_translation("signature_pending", lang),
            })

        return {
            "loan_id": loan_id,
            "pending_count": len(pending_list),
            "signatures": pending_list,
            "lang": lang,
        }


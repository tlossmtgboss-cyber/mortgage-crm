class PortalRateLimiter:
    """In-memory rate limiter for portal login and upload operations."""

    @staticmethod
    def check_login_rate_limit(email: str) -> None:
        """
        Enforce login rate limiting: max 5 attempts per hour per email.

        Raises:
            ValueError: If rate limit exceeded.
        """
        email_lower = email.strip().lower()
        now = time.time()
        cutoff = now - 3600

        _login_attempt_timestamps[email_lower] = [
            ts for ts in _login_attempt_timestamps[email_lower] if ts > cutoff
        ]

        if len(_login_attempt_timestamps[email_lower]) >= MAX_LOGIN_ATTEMPTS_PER_HOUR:
            logger.warning(f"Portal V2 login rate limit exceeded for {_mask_email(email_lower)}")
            raise ValueError("Too many login attempts. Please try again later.")

        _login_attempt_timestamps[email_lower].append(now)

    @staticmethod
    def check_upload_rate_limit(email: str) -> None:
        """
        Enforce upload rate limiting: max 20 uploads per hour per borrower.

        Raises:
            ValueError: If rate limit exceeded.
        """
        email_lower = email.strip().lower()
        now = time.time()
        cutoff = now - 3600

        _upload_timestamps[email_lower] = [
            ts for ts in _upload_timestamps[email_lower] if ts > cutoff
        ]

        if len(_upload_timestamps[email_lower]) >= MAX_UPLOADS_PER_HOUR:
            logger.warning(f"Portal V2 upload rate limit exceeded for {_mask_email(email_lower)}")
            raise ValueError("Upload rate limit exceeded. Please try again later.")

        _upload_timestamps[email_lower].append(now)

    @staticmethod
    def reset_all() -> None:
        """Reset all rate limit counters. For testing only."""
        _login_attempt_timestamps.clear()
        _upload_timestamps.clear()
        _access_codes.clear()


